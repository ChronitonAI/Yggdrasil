#!/bin/bash
# Regenerates GMP@VERSION/bundled/patches/rr-softticks-2-loops.patch (an rr software tick
# on every loop of GMP's hand-written x86-64 assembly, see gmpticks.py) and
# softticks/ticks-VERSION.json (where each tick went and why).
#
#   regen.sh [--check] VERSION [TARBALL]
#
# Extracts the release tarball (downloaded unless given; its sha256 must match common.jl's),
# applies the recipe's other patches for VERSION in order (rr-softticks-1-macros.patch with
# its tick macros among them), configures an x86-64 fat build (configure only, with a
# compiler that does not predefine __RR_SOFTTICKS__), lets gmpticks.py choose the ticks and
# writes them into the sources, and writes the difference as the patch.  Then it checks
# that every unit, expanded with the ticks on (RR_SOFTTICKS defined), still assembles: a
# tick can put a jrcxz's target out of its 8-bit reach, which rr-softticks-1-macros.patch
# answers with RR_SOFTTICK_JRCXZ/RR_SOFTTICK_FAR by hand.  With --check it writes nothing
# and fails if the committed files differ from the regenerated ones.
#
# Needs bash, curl (without TARBALL), tar with bzip2, patch, diff, sha256sum, an x86-64 gcc
# (with GNU as), m4, python3 (3.7+) and llvm-objdump ($GMPTICKS_OBJDUMP; tested with 19).
#
# For a new GMP version: run this, build with the software ticks compiler for
# x86_64-linux-gnu-rr_softticks, and run the binary tick check over the libraries (0
# findings) and GMP's make check, with the countdown armed and disarmed, for every CPU type
# of the fat build (configure --enable-fake-cpuid, GMP_CPU_TYPE).
set -euo pipefail

check=false
if [[ "${1:-}" == --check ]]; then
    check=true
    shift
fi
if [[ $# -lt 1 || $# -gt 2 ]]; then
    echo "usage: $0 [--check] VERSION [TARBALL]" >&2
    exit 2
fi
version=$1
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
recipe="$(cd "${here}/.." && pwd)/GMP@${version}"
patches="${recipe}/bundled/patches"
out="${patches}/rr-softticks-2-loops.patch"
json="${here}/ticks-${version}.json"
[[ -d "${patches}" ]] || { echo "no ${patches}" >&2; exit 1; }

url="https://gmplib.org/download/gmp/gmp-${version}.tar.bz2"
sha=$(grep -F "v\"${version}\" =>" "${here}/../common.jl" | grep -o '[0-9a-f]\{64\}' || true)
[[ -n "${sha}" ]] || { echo "no sha256 for GMP ${version} in common.jl" >&2; exit 1; }

work=$(mktemp -d)
trap 'rm -rf "${work}"' EXIT
tarball=${2:-}
if [[ -z "${tarball}" ]]; then
    tarball="${work}/gmp-${version}.tar.bz2"
    curl -fsSL -o "${tarball}" "${url}"
fi
echo "${sha}  ${tarball}" | sha256sum -c --quiet -

tar -xjf "${tarball}" -C "${work}"
mv "${work}/gmp-${version}" "${work}/src"
src="${work}/src"
for p in "${patches}"/*.patch; do
    case "$(basename "${p}")" in
        rr-softticks-2-*) continue ;;
    esac
    patch -s -p1 -d "${src}" < "${p}"
done
mkdir -p "${work}/a/mpn"
cp -R "${src}/mpn/x86_64" "${work}/a/mpn/"

cc=${CC:-gcc}
if echo | ${cc} -dM -E - | grep -q __RR_SOFTTICKS__; then
    echo "${cc} predefines __RR_SOFTTICKS__; give one that does not as CC" >&2
    exit 1
fi
mkdir "${work}/build"
(cd "${work}/build" && ../src/configure --enable-fat --build=x86_64-pc-linux-gnu \
    --host=x86_64-pc-linux-gnu CC="${cc}" > configure.log 2>&1) ||
    { tail -n 20 "${work}/build/configure.log" >&2; exit 1; }

LC_ALL=C python3 -I "${here}/gmpticks.py" plan "${src}" "${work}/build" "${work}/ticks.json"
LC_ALL=C python3 -I "${here}/gmpticks.py" apply "${work}/ticks.json" "${src}"
mkdir -p "${work}/b/mpn"
cp -R "${src}/mpn/x86_64" "${work}/b/mpn/"

# Every unit with the ticks on still assembles.
cp "${work}/build/config.m4" "${work}/build/config.m4.orig"
sed -i 's/^changequote(<,>)$/&\ndefine(<RR_SOFTTICKS>,1)/' "${work}/build/config.m4"
mkdir "${work}/asm"
fail=0
for u in "${work}"/build/mpn/*.asm; do
    n=$(basename "${u}" .asm)
    (cd "${work}/build/mpn" && m4 -DHAVE_CONFIG_H -D__GMP_WITHIN_GMP -DOPERATION_${n} -DPIC \
        "${n}.asm" > "${work}/asm/${n}.s") &&
    ${cc} -c "${work}/asm/${n}.s" -o "${work}/asm/${n}.o" 2> "${work}/asm/${n}.err" ||
        { echo "${n}: $(head -n 3 "${work}/asm/${n}.err")" >&2; fail=1; }
done
[[ ${fail} == 0 ]] || { echo "some units do not assemble with the ticks" >&2; exit 1; }
echo "$(ls "${work}"/asm/*.o | wc -l) units assemble with the ticks"

{
    cat <<EOF
Generated by G/GMP/softticks/regen.sh ${version}; do not edit by hand.

rr software ticks (rr's tracee ABI version 1) on every loop of GMP's hand-written x86-64
assembly, every CPU's (the fat build has them all), at the places softticks/gmpticks.py
chose (softticks/ticks-${version}.json lists them).  The macros come from
rr-softticks-1-macros.patch and expand to nothing unless configure found a compiler that
predefines __RR_SOFTTICKS__: without one the object code is the same.

EOF
    # Without the file times in the headers (the two lines after each `diff` line).
    (cd "${work}" && { LC_ALL=C diff -ruN a b || [[ $? == 1 ]]; }) | awk '
        /^diff / { h = 2; print; next }
        h > 0 { h--; sub(/\t.*$/, "") }
        { print }'
} > "${work}/loops.patch"

if ${check}; then
    status=0
    cmp -s "${work}/loops.patch" "${out}" || { echo "${out} differs from the regenerated patch" >&2; status=1; }
    cmp -s "${work}/ticks.json" "${json}" || { echo "${json} differs from the regenerated one" >&2; status=1; }
    [[ ${status} == 0 ]] && echo "${out} and ${json} are up to date"
    exit ${status}
fi
cp "${work}/loops.patch" "${out}"
cp "${work}/ticks.json" "${json}"
echo "wrote ${out} ($(grep -c '^+++ ' "${out}") files) and ${json}"
