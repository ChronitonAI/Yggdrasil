#!/bin/bash
# Regenerates OpenBLAS@VERSION/bundled/patches/91-rr-softticks-kernels.patch, the rr software
# ticks at the loop headers of OpenBLAS's hand-written x86-64 kernels (see asmticks.py; the
# tick macros and the function-entry ticks are the hand-written 90-rr-softticks-macros.patch).
#
#   regen.sh [--check] VERSION [TARBALL]
#
# Extracts the release tarball (downloaded unless given; its sha256 must match common.jl's),
# applies the recipe's other patches for VERSION in order, runs asmticks.py over every .S, .c
# and .h file in kernel/x86_64 and writes the difference as the patch. With --check it writes
# nothing and fails if the committed patch differs from the regenerated one. Needs bash,
# python3, curl (without TARBALL), tar, patch, diff and sha256sum.
#
# For a new OpenBLAS version: run this, build with the software ticks plugin for
# x86_64-linux-gnu-rr_softticks, and let the recipe's post-build check (softticks/check.pl)
# judge the result. The rewriter is textual; the check, on the object code, is what catches a
# loop idiom it does not know (it caught cpp jump aliases and pasted inline-asm labels).
set -euo pipefail

check=false
if [[ "${1:-}" == --check ]]; then
    check=true
    shift
fi
if [[ $# -lt 1 || $# -gt 2 ]]; then
    echo "usage: $0 [--check] VERSION [TARBALL]" >&2
    exit 2
fi
version=$1
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
recipe="$(cd "${here}/.." && pwd)/OpenBLAS@${version}"
patches="${recipe}/bundled/patches"
out="${patches}/91-rr-softticks-kernels.patch"
[[ -d "${patches}" ]] || { echo "no ${patches}" >&2; exit 1; }

url="https://github.com/OpenMathLib/OpenBLAS/releases/download/v${version}/OpenBLAS-${version}.tar.gz"
sha=$(grep -A1 -F "/v${version}/OpenBLAS-${version}.tar.gz" "${here}/../common.jl" | grep -o '[0-9a-f]\{64\}' || true)
[[ -n "${sha}" ]] || { echo "no sha256 for OpenBLAS ${version} in common.jl" >&2; exit 1; }

work=$(mktemp -d)
trap 'rm -rf "${work}"' EXIT
tarball=${2:-}
if [[ -z "${tarball}" ]]; then
    tarball="${work}/OpenBLAS-${version}.tar.gz"
    curl -fsSL -o "${tarball}" "${url}"
fi
echo "${sha}  ${tarball}" | sha256sum -c --quiet -

mkdir "${work}/src"
tar -xzf "${tarball}" -C "${work}/src"
src="${work}/src/OpenBLAS-${version}"
for p in "${patches}"/*.patch; do
    case "$(basename "${p}")" in
        9?-rr-softticks-*) continue ;;
    esac
    patch -s -p1 -d "${src}" < "${p}"
done

mkdir -p "${work}/a/kernel" "${work}/b/kernel"
cp -R "${src}/kernel/x86_64" "${work}/a/kernel/"
cp -R "${src}/kernel/x86_64" "${work}/b/kernel/"
(
    shopt -s nullglob
    cd "${work}/b"
    LC_ALL=C python3 -I "${here}/asmticks.py" kernel/x86_64/*.S kernel/x86_64/*.c kernel/x86_64/*.h
) > "${work}/asmticks.log"
tail -n 1 "${work}/asmticks.log"

{
    cat <<EOF
Generated by O/OpenBLAS/softticks/regen.sh ${version}; do not edit by hand.

Software ticks (rr's ABI version 1) at the loop headers of the hand-written x86-64 kernels:
RR_SOFTTICK after every label in a .S file that a later jump targets, RR_SOFTTICK_ASM after
every such label in an inline-asm template. Both macros come from
90-rr-softticks-macros.patch and are empty unless the compiler predefines __RR_SOFTTICKS__.

EOF
    # Without the file times in the headers (the two lines after each `diff` line).
    (cd "${work}" && { LC_ALL=C diff -ruN a b || [[ $? == 1 ]]; }) | awk '
        /^diff / { h = 2; print; next }
        h > 0 { h--; sub(/\t.*$/, "") }
        { print }'
} > "${work}/91.patch"

if ${check}; then
    if cmp -s "${work}/91.patch" "${out}"; then
        echo "${out} is up to date"
    else
        echo "${out} differs from the regenerated patch" >&2
        exit 1
    fi
else
    cp "${work}/91.patch" "${out}"
    echo "wrote ${out} ($(grep -c '^+++ ' "${out}") files)"
fi
